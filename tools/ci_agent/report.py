"""Turn a diagnosis into a PR comment and post it."""

from __future__ import annotations

import json
import os
import urllib.request

from tools.ci_agent.agent import Result

MARKER = "<!-- nrs-ci-agent -->"


def to_markdown(res: Result) -> str:
    d = res.diagnosis
    cost = f"{res.iterations} iterations, {res.input_tokens + res.output_tokens:,} tokens"
    if d is None:
        return (f"{MARKER}\n### CI failure analysis\n\nThe agent stopped without a diagnosis "
                f"(`{res.stop}`, {cost}). See the job logs.\n")
    loc = d["file"] + (f":{d['line']}" if d.get("line") else "")
    evidence = "\n".join(f"- `{e}`" if "\n" not in e else f"- ```\n{e}\n```" for e in d["evidence"])
    return (f"{MARKER}\n### CI failure analysis (automated, confidence: {d['confidence']})\n\n"
            f"**Likely root cause:** {d['summary']}\n\n"
            f"**Where:** `{loc}` &middot; category `{d['category']}`\n\n"
            f"**Evidence**\n{evidence}\n\n"
            f"<details><summary>Suggested patch</summary>\n\n```diff\n{d['suggested_patch']}\n```\n"
            f"</details>\n\n<sub>Generated by tools/ci_agent ({cost}). Verify before applying.</sub>\n")


def post_pr_comment(repo: str, pr: int, body: str, token: str) -> None:
    req = urllib.request.Request(
        f"https://api.github.com/repos/{repo}/issues/{pr}/comments",
        data=json.dumps({"body": body}).encode(),
        headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json",
                 "User-Agent": "nrs-ci-agent"},
        method="POST")
    with urllib.request.urlopen(req, timeout=30) as r:
        r.read()


def github_token() -> str | None:
    return os.environ.get("GITHUB_TOKEN") or None
